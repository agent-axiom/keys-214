GROUPS = [
    {'id': 'nature', 'name': 'Природа', 'full': 'Неживая природа и природные явления', 'glyph': '山'},
    {'id': 'plants', 'name': 'Растения', 'full': 'Растения', 'glyph': '木'},
    {'id': 'animals', 'name': 'Животные', 'full': 'Животный мир', 'glyph': '鳥'},
    {'id': 'people', 'name': 'Человек', 'full': 'Человек и его действия', 'glyph': '人'},
    {'id': 'body', 'name': 'Тело', 'full': 'Части тела', 'glyph': '手'},
    {'id': 'tools', 'name': 'Быт и труд', 'full': 'Предметы труда и быта', 'glyph': '工'},
]

facts = json.loads(FACTS.read_text())
rows = [line.split('|') for line in (ROOT / 'content.tsv').read_text().splitlines() if line.strip()]
assert len(rows) == len(facts) == 214
data = []
for row, fact in zip(rows, facts):
    number, meaning, group, mnemonic, variants = [value.strip() for value in row]
    n = int(number)
    assert n == fact['id']
    assert group in {g['id'] for g in GROUPS}
    data.append({'id': n, 'glyph': fact['glyph'], 'pinyin': READINGS.get(n, fact['kMandarin']),
                 'meaning': meaning, 'group': group, 'mnemonic': mnemonic,
                 'strokes': next(strokes for end, strokes in ENDS if n <= end),
                 'variants': variants.split() if variants else [],
                 'examples': [{'glyph': h, 'pinyin': p, 'meaning': m} for h, p, m in EXAMPLES.get(n, [])]})

(ROOT / 'dist/data.js').write_text(
    '// Unicode data used under Unicode License v3; Russian texts are original.\n'
    'export const GROUPS = ' + json.dumps(GROUPS, ensure_ascii=False) + ';\n'
    'export const RADICALS = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n')
print(f'Built {len(data)} cards, {sum(len(r["examples"]) for r in data)} examples.')
